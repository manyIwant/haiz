/**
 * Picks only the Noto Sans SC / Noto Serif SC unicode-range slices this prototype's text actually
 * uses, and writes src/styles/fonts.generated.css pointing at them. Vite then fingerprints just those
 * woff2 files into assets/. No font CDN is needed (the product's readers are in mainland China).
 *
 * On real devices the sans stack resolves to PingFang / HarmonyOS / MiSans / YaHei first and the
 * webfont is never fetched; it exists so every machine (and the Linux acceptance browser) sees
 * the same CJK glyphs. The serif is the display face and is always the webfont.
 */
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { join, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "src/styles/fonts.generated.css");

const used = new Set();
function scan(p) {
  if (!existsSync(p)) return;
  const st = statSync(p);
  if (st.isDirectory()) { for (const n of readdirSync(p)) if (!n.startsWith(".")) scan(join(p, n)); return; }
  if (!/\.(tsx?|html|json|md|css)$/.test(p) || p.endsWith("fonts.generated.css")) return;
  for (const ch of readFileSync(p, "utf8")) used.add(ch.codePointAt(0));
}
scan(join(root, "src"));
scan(join(root, "index.html"));
scan(join(root, "bench.html"));
scan(join(root, "public/data/campus.json"));
// characters people commonly type into the teacher's forms / search, so a demo stays in one face
for (const ch of "，。、；：？！“”‘’（）《》【】—…·0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ") used.add(ch.codePointAt(0));

function ranges(s) {
  return s.split(",").map((r) => {
    const m = r.trim().replace(/^U\+/i, "").split("-");
    const a = parseInt(m[0].replace(/\?/g, "0"), 16);
    const b = m[1] ? parseInt(m[1], 16) : parseInt(m[0].replace(/\?/g, "f"), 16);
    return [a, b];
  });
}

const picks = [
  { pkg: "noto-sans-sc", weights: [400, 600] },
  { pkg: "noto-serif-sc", weights: [600] },
];
let css = "/* generated by scripts/fonts.mjs — do not edit */\n";
let bytes = 0, faces = 0;
for (const { pkg, weights } of picks) {
  for (const w of weights) {
    const dir = join(root, "node_modules/@fontsource", pkg);
    const src = readFileSync(join(dir, `${w}.css`), "utf8");
    for (const block of src.split("@font-face").slice(1)) {
      const ur = /unicode-range:\s*([^;]+);/.exec(block);
      const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(block);
      if (!ur || !file) continue;
      const rs = ranges(ur[1]);
      let hit = false;
      for (const cp of used) { if (rs.some(([a, b]) => cp >= a && cp <= b)) { hit = true; break; } }
      if (!hit) continue;
      const abs = join(dir, "files", file[1]);
      bytes += statSync(abs).size; faces++;
      const fam = pkg === "noto-sans-sc" ? "Noto Sans SC" : "Noto Serif SC";
      css += `@font-face{font-family:'${fam}';font-style:normal;font-display:swap;font-weight:${w};src:url(${relative(dirname(out), abs).replace(/\\/g, "/")}) format('woff2');unicode-range:${ur[1].trim()}}\n`;
    }
  }
}
writeFileSync(out, css);
console.log(`fonts: ${used.size} distinct characters → ${faces} slices, ${(bytes / 1024).toFixed(0)} KB`);
