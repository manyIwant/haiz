#!/usr/bin/env node
// HAIZ campus spatial audit.
//
//   node tools/campus-audit/audit.mjs            print findings; exit 1 on any error
//   node tools/campus-audit/audit.mjs --strict   also exit 1 on warnings
//   node tools/campus-audit/audit.mjs --write    also write docs/campus-audit/audit-output.{json,md}
//   node tools/campus-audit/audit.mjs --json     print the machine-readable result
//   node tools/campus-audit/audit.mjs --root DIR audit another checkout
//   node tools/campus-audit/audit.mjs --allow-incomplete   run with required sources missing; the result
//                                                          is marked INCOMPLETE and exits 2 (never 0)
//
// Read-only with respect to the campus: it never edits campus data.
import fs from 'node:fs';
import path from 'node:path';
import { loadAll, ROOT } from './lib/load.mjs';
import { finding } from './lib/model.mjs';
import * as sources from './checks/sources.mjs';
import * as space from './checks/space.mjs';
import * as scale from './checks/scale.mjs';
import * as network from './checks/network.mjs';
import * as georef from './checks/georef.mjs';
import * as credibility from './checks/credibility.mjs';

export const CHECKS = { sources, space, scale, network, georef, credibility };
const ORDER = { error: 0, warn: 1, skip: 2, info: 3, pass: 4 };

export async function audit(root = ROOT, { allowIncomplete = false } = {}) {
  const S = await loadAll(root);
  const results = {};
  // Fail closed: a missing required source is an error, never a silently skipped check.
  const load = [];
  for (const m of S.missing) {
    if (m.required) load.push(finding('load', allowIncomplete ? 'warn' : 'error', m.source, `required source could not be loaded (${m.error}); the checks that depend on it did not run` + (allowIncomplete ? ' — INCOMPLETE run' : '')));
    else load.push(finding('load', 'warn', m.source, `optional source could not be loaded (${m.error}); its cross-check did not run`));
  }
  if (!S.missing.length) load.push(finding('load', 'pass', 'sources', 'every required and optional source loaded'));
  results.load = { findings: load };
  const incomplete = S.missing.some((m) => m.required);
  if (S.campus) for (const [k, m] of Object.entries(CHECKS)) {
    try { results[k] = m.run(S); } catch (e) { results[k] = { findings: [finding(k, 'error', k, 'check crashed: ' + (e.stack || e))] }; }
  }
  else for (const k of Object.keys(CHECKS)) results[k] = { findings: [finding(k, allowIncomplete ? 'warn' : 'error', k, 'not run: campus data missing')] };
  const findings = Object.values(results).flatMap((r) => r.findings);
  const counts = { error: 0, warn: 0, skip: 0, info: 0, pass: 0 };
  for (const f of findings) counts[f.severity]++;
  return { generated: new Date().toISOString(), root, incomplete, allowIncomplete, missing: S.missing, counts, results, findings };
}

export function toMarkdown(R) {
  const L = [];
  L.push('# Campus audit output', '', `Generated by \`node tools/campus-audit/audit.mjs --write\` at ${R.generated}. Do not edit by hand.`, '');
  if (R.incomplete) L.push('> **INCOMPLETE AUDIT** — required sources were missing and the run was allowed to continue. These results must not be used as acceptance evidence.', '');
  L.push('> Scope: this is a data-consistency and evidence-labelling audit of the repository. It is **not** a field survey and does not certify that the model is a 1:1 replica of the campus.', '');
  L.push(`**${R.counts.error} errors · ${R.counts.warn} warnings · ${R.counts.skip} skipped · ${R.counts.info} notes · ${R.counts.pass} passes**`, '');
  if (R.missing.length) L.push('Sources not loaded: ' + R.missing.map((m) => `\`${m.source}\` (${m.error})`).join('; '), '');
  for (const k of ['load', ...Object.keys(CHECKS)]) {
    const fs_ = R.results[k].findings.slice().sort((a, b) => ORDER[a.severity] - ORDER[b.severity]);
    L.push(`## ${k}`, '', '| | Subject | Finding |', '| --- | --- | --- |');
    for (const f of fs_) L.push(`| ${f.severity} | ${String(f.subject).replace(/\|/g, '\\|')} | ${String(f.message).replace(/\|/g, '\\|').replace(/\n/g, ' ')} |`);
    L.push('');
  }
  const rows = R.results.credibility.rows || [];
  if (rows.length) {
    L.push('## Credibility table (expanded from data/campus-credibility.json)', '', '| Subject | Aspect | Tag | Basis |', '| --- | --- | --- | --- |');
    const trees = rows.filter((r) => r.class === 'tree');
    for (const r of rows.filter((x) => x.class !== 'tree')) L.push(`| ${r.name} (\`${r.id}\`) | ${r.aspect} | **${r.tag}**${r.override ? ' ✱' : ''} | ${(r.basis || '').replace(/\|/g, '\\|')} |`);
    if (trees.length) {
      // one row per tree point is in audit-output.json; summarised here per aspect and tag
      const groups = {};
      for (const r of trees) { const k = r.aspect + '|' + r.tag; (groups[k] ||= { ...r, n: 0, overrides: 0 }).n++; if (r.override) groups[k].overrides++; }
      for (const g of Object.values(groups)) L.push(`| ${g.n} tree points (\`tree-0\` … \`tree-${(R.results.credibility.treeCount || 1) - 1}\`, one row each in audit-output.json) | ${g.aspect} | **${g.tag}**${g.overrides ? ` (${g.overrides} overridden)` : ''} | ${(g.basis || '').replace(/\|/g, '\\|')} |`);
    }
    L.push('', '✱ item-specific override of the class default.', '');
  }
  return L.join('\n');
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname);
if (isMain) {
  const args = process.argv.slice(2);
  const ri = args.indexOf('--root');
  const root = ri >= 0 ? path.resolve(args[ri + 1]) : ROOT;
  const allowIncomplete = args.includes('--allow-incomplete');
  const R = await audit(root, { allowIncomplete });
  const banner = '\n████ INCOMPLETE AUDIT: required sources missing (' + R.missing.filter((m) => m.required).map((m) => m.source).join(', ') + '). Not acceptance evidence. ████\n';
  if (R.incomplete) console.error(banner);
  if (args.includes('--json')) process.stdout.write(JSON.stringify(R, null, 2) + '\n');
  else {
    const mark = { error: '✗', warn: '!', skip: '–', info: '·', pass: '✓' };
    for (const k of ['load', ...Object.keys(CHECKS)]) {
      console.log(`\n── ${k}`);
      for (const f of R.results[k].findings.slice().sort((a, b) => ORDER[a.severity] - ORDER[b.severity])) console.log(`${mark[f.severity]} [${f.subject}] ${f.message}`);
    }
    console.log(`\n${R.counts.error} errors, ${R.counts.warn} warnings, ${R.counts.skip} skipped, ${R.counts.info} notes, ${R.counts.pass} passes`);
    if (R.incomplete) console.error(banner);
  }
  if (args.includes('--write')) {
    const dir = path.join(root, 'docs/campus-audit');
    fs.mkdirSync(dir, { recursive: true });
    const slim = { ...R, results: Object.fromEntries(Object.entries(R.results).map(([k, v]) => [k, { ...v, findings: undefined }])) };
    delete slim.root;
    fs.writeFileSync(path.join(dir, 'audit-output.json'), JSON.stringify(slim, null, 2) + '\n');
    fs.writeFileSync(path.join(dir, 'audit-output.md'), toMarkdown(R) + '\n');
  }
  // 1 = errors (or warnings with --strict); 2 = an --allow-incomplete run that skipped required sources
  process.exitCode = R.counts.error || (args.includes('--strict') && R.counts.warn) ? 1 : R.incomplete ? 2 : 0;
}
